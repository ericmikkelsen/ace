"""Generate wasm-protos.h: prototypes for engine functions that are called
without a visible declaration somewhere.  Natively those calls work by
accident of the calling convention; in WebAssembly a call whose implied
signature differs from the definition traps.  Input: the wasm-ld warnings
('function signature mismatch: NAME ... defined as ... in FILE.o')."""
import sys, re, glob, os
log = open(sys.argv[1]).read()
names = sorted(set(re.findall(r"function signature mismatch: (\w+)", log)))
srcs = glob.glob("*.c") + glob.glob("post/*.c") + glob.glob("csaw/*.c")
out, missing = [], []
for n in names:
    found = None
    for f in srcs:
        text = open(f, errors="replace").read()
        # a definition at column 0: [qualifiers/type] name(args) followed by '{' (same or next line)
        m = re.search(r"(?m)^((?:static\s+|inline\s+|extern\s+)*[A-Za-z_][\w \t\*]*?[\s\*])?" + n + r"\s*\(([^;{)]*(?:\([^)]*\)[^;{)]*)*)\)\s*\n?\s*\{", text)
        if m and not (m.group(1) or "").strip().startswith("static"):
            ret = (m.group(1) or "int ").strip() or "int"
            args = " ".join(m.group(2).split())
            found = f"{ret} {n}({args or 'void'});"
            break
    (out if found else missing).append(found or n)
with open("wasm-protos.h", "w") as h:
    h.write("/* generated by wasm/gen-protos.py -- prototypes force-included in the wasm build */\n")
    h.write("#ifndef WASM_PROTOS_H\n#define WASM_PROTOS_H\n#include <stdio.h>\n#include <wchar.h>\n")
    structs = sorted(set(re.findall(r"struct\s+(\w+)", " ".join(out))))
    h.write("".join(f"struct {t}; " for t in structs) + "\n")
    for p in out: h.write(p + "\n")
    h.write("#endif\n")
print(len(names), "names;", len(out), "prototypes;", "not found:", missing)
